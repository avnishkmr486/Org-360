const CREATED = "2025-01-02T10:00:00.000Z";

function toSteps(processId: string, steps: StepDef[]): ProcessStep[] {
  return steps.map(([name, description, minutes, opts], i) => ({
    id: `${processId}-S${i + 1}`,
    name,
    description,
    instructions: description,
    mandatory: !opts?.optional,
    expectedMinutes: minutes,
    evidenceRequired: Boolean(opts?.evidence),
    approvalRequired: Boolean(opts?.approval),
  }));
}

